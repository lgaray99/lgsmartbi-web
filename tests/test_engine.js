const assert = require('node:assert/strict');
const p = require('../assets/js/demo-engine.js');
function status(rows, name) { return rows.filter(r => r.status === name).length; }
const b = p.reconcile(p.sample.bankInternal, p.sample.bankStatement);
assert.equal(b.length, 6);
assert.equal(status(b,'Conciliado'),1);
assert.equal(status(b,'Diferencia'),1);
assert.equal(status(b,'Duplicado'),1);
assert.equal(status(b,'Solo en origen'),2);
assert.equal(status(b,'Solo en destino'),1);
const accounting = p.reconcile(p.sample.erp,p.sample.ledger);
assert.equal(status(accounting,'Conciliado'),2);
assert.equal(status(accounting,'Diferencia'),1);
assert.equal(status(accounting,'Solo en origen'),1);
assert.equal(status(accounting,'Solo en destino'),1);
const etl = p.etl(p.sample.etlRaw);
assert.equal(etl.accepted.length,3);
assert.equal(etl.rejected.length,3);
assert.equal(etl.totalAmount,300000);
const sales = p.aggregateSales('Todas');
assert.equal(sales.total,695000);
assert.equal(sales.units,18);
assert.equal(p.aggregateSales('Centro').total,420000);
const bom = p.recipeRequirements(20);
assert.deepEqual(bom.map(r=>r.quantity),[4.6,1.6,20]);
assert.throws(()=>p.recipeRequirements(-1),RangeError);
assert.equal(status(p.cardReconciliation(.02),'Conciliado'),2);
assert.equal(status(p.cardReconciliation(.02),'Diferencia'),1);
assert.equal(status(p.cardReconciliation(.02),'Solo en origen'),1);
assert.equal(status(p.cardReconciliation(.02),'Solo en destino'),1);
const csv = 'a,b,c\r\n"uno,dos",2,"dijo ""hola"""\r\n';
const parsed = p.parseCsv(csv,',');
assert.deepEqual(parsed,[['a','b','c'],['uno,dos','2','dijo "hola"']]);
const serialized = p.serializeCsv(parsed,';');
assert.deepEqual(p.parseCsv(serialized,';'),parsed);
assert.deepEqual(p.parseCsv('a\tb\n1\t2\n','\t'),[['a','b'],['1','2']]);
assert.throws(()=>p.parseCsv('"abc,def'),/Comillas sin cierre/);

// Casos frontera que afectan integridad, códigos y seguridad de las entradas.
assert.deepEqual(p.reconcile([],[]),[]);
assert.equal(p.reconcile([{ref:'001',amount:-100}],[{ref:'001',amount:-100}])[0].status,'Conciliado');
assert.equal(p.reconcile([{ref:'D',amount:5},{ref:'D',amount:5}],[{ref:'D',amount:10}])[0].status,'Duplicado');
assert.throws(()=>p.reconcile([{ref:'',amount:1}],[]),TypeError);
assert.throws(()=>p.reconcile([{ref:'A',amount:NaN}],[]),TypeError);
assert.throws(()=>p.cardReconciliation(NaN),RangeError);
assert.throws(()=>p.cardReconciliation(.31),RangeError);
assert.deepEqual(p.recipeRequirements(0).map(r=>r.quantity),[0,0,0]);
assert.throws(()=>p.recipeRequirements(.5),RangeError);
assert.throws(()=>p.recipeRequirements(100001),RangeError);
assert.equal(p.aggregateSales('Centro','Mar').total,200000);
assert.equal(p.aggregateSales('Sur','Mar').total,0); // Venta anulada.
const normalized=p.etl([{id:' A1 ',qty:2,price:10,status:'OK'},{id:'A1',qty:1,price:10,status:'OK'},null]);
assert.equal(normalized.totalAmount,20);
assert.equal(normalized.accepted[0].id,'A1');
assert.equal(normalized.rejected.length,2);
assert.throws(()=>p.etl({}),TypeError);
assert.throws(()=>p.etl([{id:'A',qty:1,price:Number.MAX_SAFE_INTEGER,status:'OK'},{id:'B',qty:1,price:Number.MAX_SAFE_INTEGER,status:'OK'}]),RangeError);
assert.throws(()=>p.reconcile([{ref:'A',amount:Number.MAX_SAFE_INTEGER},{ref:'A',amount:1}],[]),RangeError);
const input='referencia;importe\n001;100\n002;-50\n';
assert.deepEqual(p.readMovements(input),[{ref:'001',amount:100},{ref:'002',amount:-50}]);
assert.throws(()=>p.readMovements('referencia;importe\n001;\n'),/Fila 2/);
assert.throws(()=>p.readMovements('referencia;importe\n001;1.5\n'),/Fila 2/);
assert.throws(()=>p.readMovements('ref;monto\n001;100\n'),/Encabezado/);
assert.deepEqual(p.parseCsv('""'),[['']]);
assert.deepEqual(p.parseCsv('\uFEFFcodigo,detalle\r\n001,"dos\nlíneas"\r\n',','),[['codigo','detalle'],['001','dos\nlíneas']]);
assert.throws(()=>p.parseCsv('"abc"x,b'),/Carácter inesperado/);
assert.throws(()=>p.parseCsv('a"b,c'),/Comillas inesperadas/);
assert.throws(()=>p.parseCsv('a,b','"'),/Delimitador inválido/);
assert.throws(()=>p.validateCsv([]),/CSV vacío/);
assert.throws(()=>p.validateCsv([['a','a']]),/repetidos/);
assert.throws(()=>p.validateCsv([['a','b'],['1']]),/misma cantidad/);
assert.throws(()=>p.validateCsv([['a'],...Array.from({length:20001},()=>['1'])]),/20.000/);
const fs=require('node:fs'),path=require('node:path');
const fixture=p.validateCsv(p.parseCsv(fs.readFileSync(path.join(__dirname,'fixtures/ejemplo.csv'),'utf8')));
assert.equal(fixture.length,4);
assert.equal(fixture[1][0],'001');
assert.equal(fixture[2][2],'');
assert.equal(fixture[2][3],'Dos líneas\r\nlínea dos');
assert.equal(fixture[3][3],'=1+1');
assert.deepEqual(p.parseCsv(p.serializeCsv(fixture,';'),';'),fixture);
assert.throws(()=>p.validateCsv(p.parseCsv(fs.readFileSync(path.join(__dirname,'fixtures/invalido.csv'),'utf8'))),/misma cantidad/);
console.log('OK: cálculos conocidos, duplicados, faltantes, importes inválidos, BOM, filtros, integridad y límites CSV.');

